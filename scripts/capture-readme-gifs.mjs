#!/usr/bin/env node
/**
 * Captures README demo GIFs against a running `npm start` (demo mode).
 * Usage: npm start  (other terminal) →  npm run capture:gifs
 */
import { spawn } from 'node:child_process';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'docs', 'gifs');
const tmpDir = path.join(root, 'docs', '.gif-tmp');
const base = process.env.BLOG_DEMO_URL || 'http://localhost:4200/blog/';

async function sleep(ms) {
  await new Promise((r) => setTimeout(r, ms));
}

async function waitForServer(url, attempts = 90) {
  for (let i = 0; i < attempts; i++) {
    try {
      const res = await fetch(url);
      if (res.ok || res.status === 200) return;
    } catch {
      // retry
    }
    await sleep(1000);
  }
  throw new Error(`Server not reachable at ${url}`);
}

function run(cmd, args, opts = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: 'inherit', ...opts });
    child.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} exited ${code}`))));
  });
}

async function videoToGif(webm, gif) {
  const palette = webm.replace(/\.webm$/, '-palette.png');
  await run('ffmpeg', [
    '-y',
    '-i',
    webm,
    '-vf',
    'fps=12,scale=960:-1:flags=lanczos,palettegen=stats_mode=diff',
    palette
  ]);
  await run('ffmpeg', [
    '-y',
    '-i',
    webm,
    '-i',
    palette,
    '-lavfi',
    'fps=12,scale=960:-1:flags=lanczos[x];[x][1:v]paletteuse=dither=bayer:bayer_scale=5',
    gif
  ]);
  await rm(palette, { force: true });
}

async function withVideoContext(browser, name, fn) {
  const context = await browser.newContext({
    viewport: { width: 1100, height: 720 },
    recordVideo: { dir: tmpDir, size: { width: 1100, height: 720 } },
    deviceScaleFactor: 1
  });
  const page = await context.newPage();
  try {
    await fn(page);
  } finally {
    const video = page.video();
    await context.close();
    const src = await video.path();
    const destWebm = path.join(tmpDir, `${name}.webm`);
    if (path.resolve(src) !== path.resolve(destWebm)) {
      await rename(src, destWebm);
    }
    const gif = path.join(outDir, `${name}.gif`);
    await videoToGif(destWebm, gif);
    console.log('wrote', gif);
  }
}

async function main() {
  await mkdir(outDir, { recursive: true });
  await rm(tmpDir, { recursive: true, force: true });
  await mkdir(tmpDir, { recursive: true });

  console.log('Waiting for', base);
  await waitForServer(base);

  const browser = await chromium.launch({ headless: true });

  await withVideoContext(browser, 'browse-index', async (page) => {
    await page.goto(base, { waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Blog' }).waitFor();
    await sleep(600);
    await page.getByRole('button', { name: '2026' }).click();
    await sleep(700);
    await page.getByRole('button', { name: 'October' }).click();
    await sleep(900);
    await page.getByRole('button', { name: 'All' }).click();
    await sleep(500);
    await page.getByRole('button', { name: /Sort & dates|Hide sort/ }).click();
    await sleep(700);
    await page.getByRole('button', { name: /Sort & dates|Hide sort/ }).click();
    await sleep(400);
  });

  await withVideoContext(browser, 'open-post', async (page) => {
    await page.goto(base, { waitUntil: 'networkidle' });
    await page.getByRole('link', { name: 'Weekend trail notes' }).click();
    await page.getByRole('heading', { name: 'Weekend trail notes' }).waitFor();
    await sleep(500);
    await page.mouse.wheel(0, 280);
    await sleep(800);
    await page.getByRole('link', { name: 'Blog', exact: true }).click();
    await page.getByRole('heading', { name: 'Blog' }).waitFor();
    await sleep(500);
  });

  await withVideoContext(browser, 'admin-posts', async (page) => {
    await page.goto(`${base}admin`, { waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Blog Admin' }).waitFor();
    await sleep(700);
    await page.mouse.wheel(0, 420);
    await sleep(900);
    await page.getByRole('button', { name: 'Edit' }).first().click();
    await sleep(1000);
    await page.getByRole('button', { name: 'Switch to new draft' }).click();
    await sleep(700);
  });

  await browser.close();
  await writeFile(
    path.join(outDir, 'README.md'),
    '# Demo GIFs\n\nGenerated by `npm run capture:gifs` against local demo mode.\n'
  );
  await rm(tmpDir, { recursive: true, force: true });
  console.log('Done.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
